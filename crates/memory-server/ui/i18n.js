// t("Saved {n} items", { n: 3 }) -> teks terjemahan dengan {nama} diganti nilainya.
function t(s, vars) {
  let out = (LANG !== "en" && I18N[LANG] && I18N[LANG][s]) || s;
  if (vars) out = out.replace(/\{(\w+)\}/g, (m, k) => (k in vars ? String(vars[k]) : m));
  return out;
}

// Terjemahkan HTML statis: data-i18n (isi teks) dan data-i18n-<atribut> (mis. title, aria-label).
function applyI18n(root = document) {
  root.querySelectorAll("*").forEach((el) => {
    for (const a of [...el.attributes]) {
      if (a.name === "data-i18n") el.textContent = t(a.value);
      else if (a.name.startsWith("data-i18n-")) el.setAttribute(a.name.slice(10), t(a.value));
    }
  });
}

// Simpan pilihan bahasa (juga ke aplikasi desktop bila ada) lalu muat ulang UI.
async function setLang(code) {
  try { localStorage.setItem("lang", code); } catch (e) { /* abaikan */ }
  try {
    const token = localStorage.getItem("token");
    await fetch("/api/language", {
      method: "POST",
      headers: Object.assign({ "Content-Type": "application/json" }, token ? { Authorization: "Bearer " + token } : {}),
      body: JSON.stringify({ lang: code }),
    });
  } catch (e) { /* mode server: cukup disimpan di browser */ }
  location.reload();
}
